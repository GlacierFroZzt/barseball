export function resolveTeamLocation(teamId, rawName = '') {
  if (teamId && nlTeamsDatabase[teamId]) {
    return nlTeamsDatabase[teamId];
  }

  const nameLower = rawName.toLowerCase();
  for (const id in nlTeamsDatabase) {
    const item = nlTeamsDatabase[id];
    if (
      nameLower.includes(item.fullName.toLowerCase()) ||
      nameLower.includes(item.city.toLowerCase()) ||
      (nameLower.includes("braves") && id == 144) ||
      (nameLower.includes("marlins") && id == 146) ||
      (nameLower.includes("mets") && id == 121) ||
      (nameLower.includes("phillies") && id == 143) ||
      (nameLower.includes("nationals") && id == 120) ||
      (nameLower.includes("cubs") && id == 112) ||
      (nameLower.includes("reds") && id == 113) ||
      (nameLower.includes("brewers") && id == 158) ||
      (nameLower.includes("pirates") && id == 134) ||
      (nameLower.includes("cardinals") && id == 138) ||
      ((nameLower.includes("diamondbacks") || nameLower.includes("d-backs")) && id == 109) ||
      (nameLower.includes("rockies") && id == 115) ||
      (nameLower.includes("dodgers") && id == 119) ||
      (nameLower.includes("padres") && id == 135) ||
      (nameLower.includes("giants") && id == 137)
    ) {
      return item;
    }
  }

  return { fullName: rawName, state: "EE. UU.", city: "MLB", div: "Liga Nacional" };
}